var valor1 = 10;
var valor2 = "10";
var total;

// == para avaliar valor
total = (valor1 == valor2); 
alert(total);
//saida vai true ou false

// === avaliar valor e tipo
total = (valor1 === valor2);
alert(total);
//saida vai ser false 

// != é diferente
total = (valor1 != valor2);
alert(total); 
//saida vai ser true

// avaliar valor e tipo sao diferentes
total = (valor1 !== valor2);
alert(total);
//saida vai ser false 

// avaliar valor menor
total = (valor1 < valor2);
alert(total);
//saida vai ser false 

// avaliar se é maior
total = (valor1 > valor2);
alert(total);
//saida vai ser false 

//  avaliar valor menor ou igual
total = (valor1 >= valor2);
alert(total);
//saida vai ser true

